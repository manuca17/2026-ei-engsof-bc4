namespace BlazorProject.Services;

public sealed class LanguageService
{
    private string _currentLanguage = "pt";

    public string CurrentLanguage => _currentLanguage;

    public event Action? LanguageChanged;

    public void Init(string languageCode)
    {
        if (string.IsNullOrWhiteSpace(languageCode) || !_translations.ContainsKey(languageCode))
            languageCode = "pt";
        _currentLanguage = languageCode;
    }

    public void SetLanguage(string languageCode)
    {
        if (string.IsNullOrWhiteSpace(languageCode) || !_translations.ContainsKey(languageCode))
            languageCode = "pt";
        if (_currentLanguage == languageCode) return;
        _currentLanguage = languageCode;
        LanguageChanged?.Invoke();
    }

    public string T(string key)
    {
        if (_translations.TryGetValue(_currentLanguage, out var langDict) &&
            langDict.TryGetValue(key, out var value))
            return value;
        // fallback to Portuguese
        if (_translations.TryGetValue("pt", out var ptDict) &&
            ptDict.TryGetValue(key, out var ptValue))
            return ptValue;
        return key;
    }

